const {chromium} = require(process.env.PLAYWRIGHT_MODULE || '../tooling/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async()=>{
  const errors=[];
  const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  page.on('pageerror',e=>errors.push(e.message));
  const host=process.env.TEST_HOST || 'http://127.0.0.1:8000';
  await page.goto(host+'/releases.html');
  await page.locator('#candidate option').first().waitFor({state:'attached'});
  const experiments=await page.request.get(host+'/api/public/experiments').then(r=>r.json());
  const byRevision=revision=>experiments.find(e=>e.revision===revision).id;
  await page.locator('#baseline').selectOption(byRevision('baseline-v1'));
  await page.locator('#candidate').selectOption(byRevision('optimized-v2'));
  await page.locator('#compare').click();
  await page.locator('#report h2.pass').waitFor();
  assert.match(await page.locator('#report').innerText(),/放行/);
  await page.locator('#candidate').selectOption(byRevision('regressed-v3'));
  await page.locator('#compare').click();
  await page.locator('#report h2.block').waitFor();
  assert.equal(await page.locator('#report tbody tr').count(),6);
  fs.mkdirSync(path.join(__dirname,'../artifacts'),{recursive:true});
  await page.screenshot({path:path.join(__dirname,'../artifacts/release-console.png'),fullPage:true});
  const traceHref=await page.locator('#report tbody a').last().getAttribute('href');
  await page.goto(host+traceHref);
  await page.locator('#capture').waitFor();
  assert.match(await page.locator('#detail').innerText(),/regressed-v3/);
  await page.screenshot({path:path.join(__dirname,'../artifacts/trace-detail.png'),fullPage:true});
  page.on('dialog',d=>d.accept('1-3个工作日'));
  await page.locator('#capture').click();
  await page.locator('#capture-message').filter({hasText:'数据集已创建'}).waitFor();
  await page.goto(host+'/releases.html');
  await page.locator('#candidate option').first().waitFor({state:'attached'});
  await page.locator('[data-experiment]').first().click();
  await page.locator('#results:not([hidden])').waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:path.join(__dirname,'../artifacts/release-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser smoke PASS: gate pass/block, 6 regression pairs, trace drilldown, dataset capture, per-case results, mobile overflow, zero page errors.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
